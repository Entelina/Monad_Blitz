import fs from "fs";
import path from "path";
import hre from "hardhat";

async function main() {
  const [deployer] = await hre.viem.getWalletClients();
  const publicClient = await hre.viem.getPublicClient();
  const chainId = await publicClient.getChainId();

  console.log("Deploying TaskRailEscrow...");
  console.log("  Network:", hre.network.name, `(chainId=${chainId})`);
  console.log("  Deployer:", deployer.account.address);

  const balance = await publicClient.getBalance({ address: deployer.account.address });
  console.log("  Balance:", Number(balance) / 1e18, "MON");

  const escrow = await hre.viem.deployContract("TaskRailEscrow");
  console.log("TaskRailEscrow deployed to:", escrow.address);

  const artifact = await hre.artifacts.readArtifact("TaskRailEscrow");

  const deployment = {
    network: hre.network.name,
    chainId,
    address: escrow.address,
    deployer: deployer.account.address,
    deployedAt: new Date().toISOString(),
  };

  const outDir = path.join(__dirname, "..", "deployments");
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(
    path.join(outDir, `${hre.network.name}.json`),
    JSON.stringify(deployment, null, 2) + "\n",
    "utf8"
  );

  // Sync ABI + address to web/src/lib/generated.ts if web/ exists
  const webLibDir = path.join(__dirname, "..", "..", "web", "src", "lib");
  if (fs.existsSync(webLibDir)) {
    const content = `// Auto-generated by contracts/scripts/deploy.ts
export const TASKRAIL_CHAIN_ID = ${chainId} as const;
export const TASKRAIL_CONTRACT_ADDRESS = "${escrow.address}" as \`0x\${string}\`;
export const TASKRAIL_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
    fs.writeFileSync(path.join(webLibDir, "generated.ts"), content, "utf8");
    console.log("Synced ABI and address to web/src/lib/generated.ts");
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
